-- ---------- Categories ------------------------------------------------
create table if not exists public.blog_categories (
  id             bigint generated by default as identity primary key,
  name           text not null,
  slug           text unique,
  -- The AI reads "name: description" to decide which category fits a post,
  -- so a clear description directly improves categorisation.
  description    text,
  h1             text,
  markdown_intro text,
  created_at     timestamptz not null default now()
);

-- ---------- Posts -----------------------------------------------------
create table if not exists public.blog_posts (
  id               bigint generated by default as identity primary key,
  title            text not null,
  slug             text not null unique,
  content          text,                       -- markdown
  meta_description text,
  status           text not null default 'draft'
                   check (status in ('draft', 'published', 'draft_error')),
  language         text not null default 'en',
  featured_image   text,
  categories       bigint[] default '{}',
  tip              text,                       -- short "pro tip" box
  noindex          boolean not null default false,
  source           text not null default 'ai', -- 'ai' | 'manual'
  keyword          text,                       -- target keyword it was written for
  created_at       timestamptz not null default now(),
  published_at     timestamptz,
  last_modified    timestamptz not null default now()
);

create index if not exists blog_posts_status_lang_idx
  on public.blog_posts (status, language, published_at desc);

-- Keep last_modified honest (feeds sitemap <lastmod> and IndexNow).
create or replace function public.touch_blog_post()
returns trigger language plpgsql as $$
begin
  new.last_modified := now();
  if new.status = 'published' and new.published_at is null then
    new.published_at := now();
  end if;
  return new;
end $$;

drop trigger if exists blog_posts_touch on public.blog_posts;
create trigger blog_posts_touch
  before insert or update on public.blog_posts
  for each row execute function public.touch_blog_post();

-- ---------- Media library ---------------------------------------------
create table if not exists public.blog_media (
  id         bigint generated by default as identity primary key,
  src        text not null,
  alt        text,
  created_at timestamptz not null default now()
);

-- ---------- Keyword queue ---------------------------------------------
create table if not exists public.keyword_queue (
  id           bigint generated by default as identity primary key,
  keyword      text not null,
  language     text not null default 'en',
  position     integer not null default 0,
  status       text not null default 'pending'
               check (status in ('pending', 'processing', 'done', 'failed')),
  attempts     integer not null default 0,
  last_error   text,
  post_id      bigint references public.blog_posts (id) on delete set null,
  created_at   timestamptz not null default now(),
  started_at   timestamptz,
  processed_at timestamptz,
  unique (keyword, language)
);

create index if not exists keyword_queue_pending_idx
  on public.keyword_queue (status, position);

-- Atomically claim the next keyword. `for update skip locked` means two cron
-- runs that overlap can never grab the same keyword. Keywords stuck in
-- 'processing' for 15+ minutes (a crashed run) are picked up again.
create or replace function public.claim_next_keyword(max_attempts integer default 3)
returns setof public.keyword_queue
language plpgsql as $$
begin
  return query
  update public.keyword_queue q
     set status = 'processing',
         started_at = now(),
         attempts = q.attempts + 1
   where q.id = (
     select id from public.keyword_queue
      where (status = 'pending'
             or (status = 'processing' and started_at < now() - interval '15 minutes'))
        and attempts < max_attempts
      order by position asc, id asc
      limit 1
      for update skip locked
   )
  returning q.*;
end $$;

-- ---------- Row Level Security ----------------------------------------
-- The admin app uses the service-role key (bypasses RLS). The public website
-- uses the anon key and may only READ published, indexable content.
alter table public.blog_posts      enable row level security;
alter table public.blog_categories enable row level security;
alter table public.blog_media      enable row level security;
alter table public.keyword_queue   enable row level security;

drop policy if exists "public reads published posts" on public.blog_posts;
create policy "public reads published posts" on public.blog_posts
  for select to anon, authenticated
  using (status = 'published');

drop policy if exists "public reads categories" on public.blog_categories;
create policy "public reads categories" on public.blog_categories
  for select to anon, authenticated using (true);

drop policy if exists "public reads media" on public.blog_media;
create policy "public reads media" on public.blog_media
  for select to anon, authenticated using (true);
-- keyword_queue: no public policies at all = invisible to anon.

revoke execute on function public.claim_next_keyword(integer) from public, anon, authenticated;

